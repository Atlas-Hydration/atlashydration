const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync('app/lib/checkoutAttribution.ts', 'utf8');
const code = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.CommonJS}}).outputText;
const storage = () => { const values = new Map(); return {getItem: k => values.get(k) ?? null, setItem: (k,v) => values.set(k,v), removeItem: k => values.delete(k)}; };
const context = {exports: {}, URL, Date, localStorage: storage(), sessionStorage: storage(), window: {location: {href: 'https://atlas-hydration.com/?utm_source=facebook&utm_campaign=kit&fbclid=unit_test_click&email=private@example.com'}}};
vm.runInNewContext(code, context);
const {captureCheckoutAttribution: capture, buildOneTimeCheckoutUrl: build} = context.exports;
const line = ['67691017732170:1'];
capture(false);
assert.equal(context.sessionStorage.getItem('atlas_checkout_attribution'), null);
assert.equal(new URL(build(line)).searchParams.has('attribution/click_id_value'), false);
context.localStorage.setItem('atlas_cookie_consent','accepted');
capture(true);
context.window.location.href = 'https://atlas-hydration.com/products/strawberry-lemonade';
capture(false); // Initial React render must not clear an already accepted session.
let url = new URL(build(line));
assert.equal(url.pathname, '/buy/67691017732170:1');
assert.equal(url.searchParams.get('attribution/click_id_value'), 'unit_test_click');
assert.equal(url.searchParams.get('attribution/utm_campaign'), 'kit');
assert.equal(url.toString().includes('private'), false);
assert.equal(url.searchParams.get('ucp/version'), '2026-08-25');
context.localStorage.setItem('atlas_cookie_consent','declined');
capture(false);
assert.equal(new URL(build(line)).searchParams.has('attribution/utm_source'), false);
assert.equal(context.sessionStorage.getItem('atlas_checkout_attribution'), null);
context.localStorage.setItem('atlas_cookie_consent','accepted');
context.sessionStorage.setItem('atlas_checkout_attribution', JSON.stringify({savedAt: Date.now()-86400001,fields:{utm_source:'stale'}}));
assert.equal(new URL(build(line)).searchParams.has('attribution/utm_source'), false);
context.sessionStorage.setItem('atlas_checkout_attribution', 'broken');
assert.equal(new URL(build(line)).pathname, '/buy/67691017732170:1');
context.window.location.href = 'https://atlas-hydration.com/?utm_campaign='+encodeURIComponent('日'.repeat(160));
capture(true);
assert.ok(build(line).length <= 2048);
console.log('Checkout attribution: consent, revocation, cross-page retention, allowlist, expiry, corruption and URL budget passed.');
